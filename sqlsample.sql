-- -----------------------------------------------------------------------------
-- VIEW TỔNG HỢP TIỆN DỤNG (travel_places_view) VỚI SECURITY_INVOKER = ON
-- -----------------------------------------------------------------------------
DROP VIEW IF EXISTS public.travel_places_view CASCADE;

CREATE OR REPLACE VIEW public.travel_places_view WITH (security_invoker = on) AS
SELECT
  l.id,
  l.name,
  l.group_id,
  l.group_id AS "group",
  g.name AS group_name,
  g.icon AS group_icon,
  l.city_id,
  c.name AS city_name,
  l.category,
  l.lat,
  l.lng,
  l.address,
  l.phone,
  l.contact,
  l.checked,
  l.visited_at,
  l.is_favorite,
  l.is_deleted,
  l.deleted_at,
  COALESCE(d.rating, 4.8) AS rating,
  COALESCE(d.price_range, ''::character varying) AS price_range,
  COALESCE(d.opening_hours, ''::character varying) AS opening_hours,
  COALESCE(d.best_time_to_visit, ''::character varying) AS best_time_to_visit,
  COALESCE(d.notes, ''::text) AS notes,
  COALESCE(d.travel_tips, ''::text) AS travel_tips,
  COALESCE(d.specialties, ''::text) AS specialties,
  COALESCE(d.thumbnail_url, ''::text) AS thumbnail_url,
  CASE 
    WHEN d.gallery_urls IS NULL THEN '[]'::jsonb 
    ELSE to_jsonb(d.gallery_urls) 
  END AS gallery_urls,
  COALESCE(d.website_url, ''::text) AS website_url,
  l.created_at,
  l.updated_at
FROM public.travel_locations l
LEFT JOIN public.travel_location_details d ON l.id::text = d.location_id::text
LEFT JOIN public.travel_groups g ON l.group_id::text = g.id::text
LEFT JOIN public.travel_cities c ON l.city_id::text = c.id::text
WHERE l.is_deleted = FALSE;

-- -----------------------------------------------------------------------------
-- HOÀN TẤT NẠP DỮ LIỆU MẪU
-- -----------------------------------------------------------------------------
SELECT 
  (SELECT count(*) FROM public.travel_locations WHERE is_deleted = false) AS total_locations,
  (SELECT count(*) FROM public.travel_groups) AS total_groups,
  (SELECT count(*) FROM public.travel_trips) AS total_trips,
  (SELECT count(*) FROM public.travel_reviews_logs) AS total_reviews,
  (SELECT count(*) FROM public.travel_expenses) AS total_expenses;
