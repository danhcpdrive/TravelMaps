-- TRAVEL MAPS - BẢN SQL ĐẦY ĐỦ KHỞI TẠO CƠ SỞ DỮ LIỆU & DỮ LIỆU MẪU (sqlsample.sql)
-- =============================================================================
-- Hướng dẫn: Mở Supabase Dashboard -> Chọn dự án -> SQL Editor -> Dán toàn bộ file này -> Nhấn Run
-- Tất cả các bảng sử dụng khóa chính ID kiểu BIGINT (INT) tự động tăng dần (Identity Column)
-- Script sử dụng 'ON CONFLICT' an toàn, có thể chạy lại nhiều lần mà không sợ lỗi trùng lặp.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- 1. CẤU TRÚC BẢNG DỮ LIỆU CHUẨN (DATABASE SCHEMA DDL - CỘT ID DÙNG BIGINT IDENTITY)
-- =============================================================================

-- 1.1. BẢNG NGƯỜI DÙNG & TÀI KHOẢN (travel_users)
CREATE TABLE IF NOT EXISTS public.travel_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  password VARCHAR(255),
  role VARCHAR(50) DEFAULT 'user' CHECK (role IN ('viewer', 'user', 'admin')),
  avatar_url TEXT,
  phone VARCHAR(50),
  status VARCHAR(50) DEFAULT 'active',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.2. BẢNG PHÂN NHÓM DỊCH VỤ (travel_groups)
CREATE TABLE IF NOT EXISTS public.travel_groups (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  icon VARCHAR(50) NOT NULL,
  badge_bg VARCHAR(100) NOT NULL,
  marker_color VARCHAR(50) NOT NULL,
  description TEXT,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.3. BẢNG DANH MỤC THÀNH PHỐ / TỈNH THÀNH (travel_cities)
CREATE TABLE IF NOT EXISTS public.travel_cities (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  code VARCHAR(20),
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.4. BẢNG ĐỊA ĐIỂM CỐT LÕI (travel_locations)
CREATE TABLE IF NOT EXISTS public.travel_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  group_id VARCHAR(50) REFERENCES public.travel_groups(id) ON DELETE SET NULL,
  city_id VARCHAR(50) REFERENCES public.travel_cities(id) ON DELETE SET NULL,
  category VARCHAR(100) DEFAULT 'Địa điểm',
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  address TEXT NOT NULL,
  phone VARCHAR(100),
  contact VARCHAR(255),
  checked BOOLEAN DEFAULT FALSE,
  visited_at TIMESTAMPTZ,
  is_favorite BOOLEAN DEFAULT FALSE,
  is_deleted BOOLEAN DEFAULT FALSE,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.5. BẢNG CHI TIẾT ĐỊA ĐIỂM (travel_location_details)
CREATE TABLE IF NOT EXISTS public.travel_location_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT UNIQUE REFERENCES public.travel_locations(id) ON DELETE CASCADE,
  rating NUMERIC(3, 1) DEFAULT 4.5,
  price_range VARCHAR(100),
  opening_hours VARCHAR(100),
  best_time_to_visit VARCHAR(255),
  notes TEXT,
  travel_tips TEXT,
  specialties TEXT,
  thumbnail_url TEXT,
  gallery_urls TEXT[] DEFAULT ARRAY[]::TEXT[],
  website_url TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.6. BẢNG THẺ GẮN TAGS (travel_tags & travel_location_tags)
CREATE TABLE IF NOT EXISTS public.travel_tags (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  color VARCHAR(50) NOT NULL,
  icon VARCHAR(50),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.travel_location_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT REFERENCES public.travel_locations(id) ON DELETE CASCADE,
  tag_id VARCHAR(50) REFERENCES public.travel_tags(id) ON DELETE CASCADE,
  UNIQUE(location_id, tag_id)
);

-- 1.7. BẢNG LỊCH TRÌNH CHUYẾN ĐI (travel_trips & travel_trip_stops)
CREATE TABLE IF NOT EXISTS public.travel_trips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100),
  user_email VARCHAR(255),
  user_name VARCHAR(255),
  title VARCHAR(255) NOT NULL,
  description TEXT,
  start_date DATE,
  end_date DATE,
  budget NUMERIC(15, 2) DEFAULT 0,
  cover_image TEXT,
  status VARCHAR(50) DEFAULT 'planning' CHECK (status IN ('planning', 'ongoing', 'completed')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.travel_trip_stops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT REFERENCES public.travel_trips(id) ON DELETE CASCADE,
  location_id BIGINT REFERENCES public.travel_locations(id) ON DELETE CASCADE,
  day_number INT DEFAULT 1,
  visit_time VARCHAR(50),
  order_index INT DEFAULT 1,
  transport_mode VARCHAR(50) DEFAULT 'driving',
  stop_notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.8. BẢNG NHẬT KÝ & ĐÁNH GIÁ (travel_reviews_logs)
CREATE TABLE IF NOT EXISTS public.travel_reviews_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100),
  user_email VARCHAR(255),
  user_name VARCHAR(255),
  location_id BIGINT REFERENCES public.travel_locations(id) ON DELETE CASCADE,
  visited_at TIMESTAMPTZ DEFAULT NOW(),
  rating NUMERIC(3, 1) DEFAULT 5,
  actual_expense NUMERIC(15, 2) DEFAULT 0,
  review_text TEXT,
  weather VARCHAR(100),
  companion VARCHAR(100),
  photos TEXT[] DEFAULT ARRAY[]::TEXT[],
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.9. BẢNG SỔ CHI TIÊU (travel_expenses)
CREATE TABLE IF NOT EXISTS public.travel_expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR(100),
  user_email VARCHAR(255),
  user_name VARCHAR(255),
  trip_id BIGINT REFERENCES public.travel_trips(id) ON DELETE SET NULL,
  location_id BIGINT REFERENCES public.travel_locations(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  category VARCHAR(50) DEFAULT 'food',
  amount NUMERIC(15, 2) DEFAULT 0,
  payment_method VARCHAR(50) DEFAULT 'cash',
  expense_date TIMESTAMPTZ DEFAULT NOW(),
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.10. BẢNG BÁO CÁO SAI SÓT / VI PHẠM (travel_reports)
CREATE TABLE IF NOT EXISTS public.travel_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT NOT NULL,
  location_name VARCHAR(255) NOT NULL,
  location_address TEXT,
  reported_by_user_id VARCHAR(100),
  reported_by_user_name VARCHAR(255),
  reported_by_user_email VARCHAR(255),
  reason VARCHAR(100) NOT NULL,
  description TEXT,
  status VARCHAR(50) DEFAULT 'pending' CHECK (status IN ('pending', 'resolved', 'dismissed')),
  admin_note TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.11. BẢNG NHẬT KÝ KIỂM TOÁN (travel_audit_logs)
CREATE TABLE IF NOT EXISTS public.travel_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name VARCHAR(100) NOT NULL,
  record_id VARCHAR(100) NOT NULL,
  action VARCHAR(50) NOT NULL,
  old_data JSONB,
  new_data JSONB,
  changed_by VARCHAR(255),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- CHỈ MỤC TỐI ƯU
CREATE INDEX IF NOT EXISTS idx_travel_locations_city ON public.travel_locations(city_id);
CREATE INDEX IF NOT EXISTS idx_travel_locations_group ON public.travel_locations(group_id);
CREATE INDEX IF NOT EXISTS idx_travel_locations_coords ON public.travel_locations(lat, lng);
CREATE INDEX IF NOT EXISTS idx_travel_location_details_loc ON public.travel_location_details(location_id);
CREATE INDEX IF NOT EXISTS idx_travel_location_tags_loc ON public.travel_location_tags(location_id);
CREATE INDEX IF NOT EXISTS idx_travel_trip_stops_trip ON public.travel_trip_stops(trip_id);
CREATE INDEX IF NOT EXISTS idx_travel_reviews_loc ON public.travel_reviews_logs(location_id);
CREATE INDEX IF NOT EXISTS idx_travel_expenses_trip ON public.travel_expenses(trip_id);

